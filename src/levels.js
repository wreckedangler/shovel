export const ROWS = 14; // Standardhöhe; Levels dürfen höher sein (siehe 1-3)

function seg(...rows) {
  while (rows.length < ROWS) rows.unshift('');
  return rows;
}
function build(segs) {
  const out = Array.from({ length: ROWS }, () => '');
  for (const s of segs) {
    const w = Math.max(...s.map(r => r.length));
    s.forEach((r, i) => { out[i] += r.padEnd(w, '.'); });
  }
  return out;
}
