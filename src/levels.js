import { generateLevel } from './gen.js';
const genCache = new Map();
// Generierte Levels haben die Kennung ∞<Tiefe>-<Seed>
export const levelById = id => {
  const l = LEVELS.find(l => l.id === id); if (l) return l;
  const m = /^∞(\d+)-(\d+)$/.exec(id); if (!m) return undefined;
  if (!genCache.has(id)) {
    const depth = +m[1], seed = +m[2];
    if (depth % 10 === 0) {
      // Wächter alle 10 Tiefen: eine der Boss-Arenen, jedes Mal stärker
      const bosses = ['1-B', '2-B', '3-B'], b = LEVELS.find(l => l.id === bosses[(depth / 10 - 1 + seed) % 3]);
      genCache.set(id, { ...b, id, name: 'Wächter der Tiefe ' + depth, gen: true, seed, depth, style: 'arena', bossTier: depth / 10, biome: 'Wächterhalle', par: b.par + 20, elite: 0 });
    } else genCache.set(id, generateLevel(seed, depth));
  }
  return genCache.get(id);
};
